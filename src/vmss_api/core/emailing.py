"""Shared SMTP-sending primitive (add-background-jobs-and-integration-tests
design.md Decision 4). Extracted out of `invitations/notifications.py` so
`reports/tasks.py` doesn't duplicate the `aiosmtplib` call — the two
features have nothing else in common (no shared template/multi-channel
abstraction), so this stays a plain sender, not a `notifications/` package.
"""

from collections.abc import Sequence
from email.message import EmailMessage
from email.utils import formataddr
from pathlib import Path
from typing import Protocol

import aiosmtplib

from vmss_api.core.config import settings
from vmss_api.core.logging import logger


class Attachment(Protocol):
    content: bytes
    filename: str
    mime_type: str


class InlineImage(Protocol):
    """An image the HTML body references as `<img src="cid:{cid}">` —
    delivered as a `multipart/related` part of the HTML alternative so mail
    clients render it without loading anything remote (email-notifications
    "The Sender Interface Supports Inline Images").
    """

    content: bytes
    mime_type: str
    cid: str


class EmailSender(Protocol):
    async def send(
        self,
        *,
        to: str,
        subject: str,
        body: str,
        html_body: str | None = None,
        attachment: "Attachment | None" = None,
        inline_images: "Sequence[InlineImage]" = (),
    ) -> None: ...


class _Attachment:
    def __init__(self, content: bytes, filename: str, mime_type: str) -> None:
        self.content = content
        self.filename = filename
        self.mime_type = mime_type


def make_attachment(content: bytes, filename: str, mime_type: str) -> _Attachment:
    return _Attachment(content, filename, mime_type)


class _InlineImage:
    def __init__(self, content: bytes, mime_type: str, cid: str) -> None:
        self.content = content
        self.mime_type = mime_type
        self.cid = cid


def make_inline_image(content: bytes, mime_type: str, cid: str) -> _InlineImage:
    return _InlineImage(content, mime_type, cid)


# Referenced by `base.html` as `cid:{BRAND_LOGO_CID}` whenever the tenant
# has no logo of its own (refine-email-templates-and-visimio-brand design.md
# Decision 5). Generated by `scripts/build_brand_assets.py` from the source
# raster; read once.
BRAND_LOGO_CID = "visimio-logo@vmss"
_BRAND_LOGO_PNG = (Path(__file__).parent / "email_assets" / "visimio-logo-on-dark.png").read_bytes()


def build_message(
    *,
    to: str,
    subject: str,
    body: str,
    html_body: str | None = None,
    attachment: "Attachment | None" = None,
    inline_images: "Sequence[InlineImage]" = (),
    brand_logo: bool = True,
) -> EmailMessage:
    """Split out of `SmtpEmailSender.send` so the MIME structure is
    unit-testable without an SMTP server. `brand_logo` attaches the Visimio
    header logo as one more related part whenever the HTML body references
    it, so callers never have to know which header variant the template
    chose.
    """
    message = EmailMessage()
    message["From"] = formataddr((settings.smtp_from_name, settings.smtp_from_address))
    message["To"] = to
    message["Subject"] = subject
    message.set_content(body)
    if html_body is not None:
        # `set_content` above becomes the `text/plain` part of a
        # `multipart/alternative` message; `add_alternative` adds the
        # `text/html` part a capable mail client prefers to render
        # (role-based-invitation-workflow, `email-notifications`
        # capability's "every rendered email SHALL also carry a
        # plain-text fallback part").
        message.add_alternative(html_body, subtype="html")
        # Only when referenced: an unreferenced related part is shown as a
        # stray attachment by some clients (tenant-logo emails don't use it).
        if brand_logo and f"cid:{BRAND_LOGO_CID}" in html_body:
            inline_images = [
                *inline_images,
                _InlineImage(_BRAND_LOGO_PNG, "image/png", BRAND_LOGO_CID),
            ]
        if inline_images:
            # Inline images only make sense relative to an HTML part, so
            # they're attached to it (turning it into `multipart/related`)
            # rather than to the message root — the structure Gmail,
            # Outlook, and Apple Mail all render inline.
            html_part = message.get_body(preferencelist=("html",))
            assert html_part is not None  # just added by `add_alternative`
            for image in inline_images:
                maintype, _, subtype = image.mime_type.partition("/")
                html_part.add_related(
                    image.content,
                    maintype=maintype,
                    subtype=subtype,
                    cid=f"<{image.cid}>",
                    disposition="inline",
                )
    if attachment is not None:
        maintype, _, subtype = attachment.mime_type.partition("/")
        message.add_attachment(
            attachment.content,
            maintype=maintype,
            subtype=subtype,
            filename=attachment.filename,
        )
    return message


class SmtpEmailSender:
    """Design.md Decision 4 — SMTP against whatever mail server `settings`
    points at (a local dev mail-catcher by default). Swapping to a
    transactional-email provider's API later is a new `EmailSender`
    implementation, not a call-site change.
    """

    async def send(
        self,
        *,
        to: str,
        subject: str,
        body: str,
        html_body: str | None = None,
        attachment: "Attachment | None" = None,
        inline_images: "Sequence[InlineImage]" = (),
    ) -> None:
        message = build_message(
            to=to,
            subject=subject,
            body=body,
            html_body=html_body,
            attachment=attachment,
            inline_images=inline_images,
        )
        # aiosmtplib attempts an AUTH login the moment `username` is a
        # non-None value, including an empty string — which an env var set
        # to `SMTP_USERNAME=` (present-but-blank, not absent) produces. The
        # local dev mail-catcher (mailhog/mailpit) doesn't support AUTH, so
        # an empty-but-set credential must be treated the same as unset.
        username = settings.smtp_username or None
        password = settings.smtp_password or None
        try:
            errors, queue_response = await aiosmtplib.send(
                message,
                hostname=settings.smtp_host,
                port=settings.smtp_port,
                username=username,
                password=password,
                start_tls=settings.smtp_use_tls,
            )
            # `queue_response` is the SMTP server's final reply (usually
            # something like "250 2.0.0 Ok: queued as <id>") — the join key
            # onto the mail server's own log/queue when a message is
            # accepted here but never lands in an inbox
            # (`security-architecture.md` §5 / `logging-observability.md`
            # §3: this is the operational trail an admin needs to correlate
            # "app says sent" against "mail server says delivered"). `errors`
            # is normally empty here — `aiosmtplib.send` raises
            # `SMTPRecipientsRefused` instead when the lone recipient this
            # sender always calls with is rejected — but is logged
            # defensively rather than assumed impossible.
            if errors:
                logger.warning(
                    "smtp_email_dispatch_partial_failure",
                    smtp_host=settings.smtp_host,
                    smtp_port=settings.smtp_port,
                    recipient_count=len(errors),
                )
            else:
                logger.info(
                    "smtp_email_dispatch_succeeded",
                    smtp_host=settings.smtp_host,
                    smtp_port=settings.smtp_port,
                    queue_response=queue_response,
                )
        except aiosmtplib.SMTPException as exc:
            # No recipient address here — the enqueuing task already binds
            # tenant/invitation context (logging-observability.md §2), and
            # that's enough to locate the record without logging PII.
            logger.warning(
                "smtp_email_dispatch_failed",
                smtp_host=settings.smtp_host,
                smtp_port=settings.smtp_port,
                exception_type=type(exc).__name__,
                error=str(exc),
            )
            raise


email_sender: EmailSender = SmtpEmailSender()
